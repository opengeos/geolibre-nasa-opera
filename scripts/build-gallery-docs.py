"""Generate the gallery page of the docs site from ``gallery/gallery.json``.

Writes ``docs/gallery.md``: one section per theme, one card per project with
its screenshot from assets.geolibre.app, a caption, and links to the live map
and its share.geolibre.app page. Run it after editing the JSON; pass
``--check`` to fail when the committed page is out of date.
"""

import html
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "gallery" / "gallery.json"
OUT = ROOT / "docs" / "gallery.md"

HEADER = """---
title: Gallery
icon: lucide/images
---

<!-- Generated by scripts/build-gallery-docs.py from gallery/gallery.json. Do not edit by hand. -->

# Gallery

{count} interactive maps of NASA OPERA products: surface water, vegetation
disturbance, SAR backscatter, and ground displacement, from 2022 to the
floods and fires of 2026. Each one is a GeoLibre project that renders OPERA
rasters straight from NASA GIBS or, through
[titiler-cmr](https://github.com/developmentseed/titiler-cmr), from the
original granules in NASA CMR, the same path the plugin's **Display** button
uses. **Click a map to open it live**, swipe the before-and-after pairs, or
fork it on share.geolibre.app to make it your own.

[Browse the collection on share.geolibre.app]({collection}){{ .md-button .md-button--primary }}
[Build your own with the plugin](install.md){{ .md-button }}

Jump to a theme: {jump}
"""


def anchor(title):
    """Return the heading anchor Zensical generates for a title.

    Args:
        title: The heading text.

    Returns:
        The lower-cased, hyphenated anchor id.
    """
    return "-".join(
        "".join(c for c in title.lower() if c.isalnum() or c == " ").split()
    )


def card(project, config):
    """Render one project as an HTML gallery card.

    Args:
        project: A project entry from the gallery JSON.
        config: The whole gallery JSON, for the owner and asset base URL.

    Returns:
        The card HTML.
    """
    slug = project["slug"]
    title = html.escape(project["title"])
    share = f"https://share.geolibre.app/{config['owner']}/{slug}"
    live = f"https://web.geolibre.app/?url={config['assets']}/projects/{slug}.geolibre.json"
    image = f"{config['assets']}/thumbnails/{slug}.webp"
    return f"""<div class="gallery-card">
<a class="gallery-thumb" href="{live}"><img src="{image}" alt="Map: {title}" loading="lazy"></a>
<div class="gallery-body">
<p class="gallery-title"><a href="{live}">{title}</a></p>
<p class="gallery-caption">{html.escape(project["caption"])}</p>
<p class="gallery-meta"><span class="gallery-chip">OPERA {html.escape(project["product"])}</span>
<span class="gallery-chip">{html.escape(project["date"])}</span>
<a href="{share}">Share page</a></p>
</div>
</div>"""


def render(config):
    """Render the whole gallery page.

    Args:
        config: The gallery JSON.

    Returns:
        The Markdown page text.
    """
    themes = config["themes"]
    jump = " · ".join(f"[{t['title']}](#{anchor(t['title'])})" for t in themes)
    parts = [
        HEADER.format(
            count=len(config["projects"]), collection=config["collection"], jump=jump
        )
    ]
    for theme in themes:
        projects = [p for p in config["projects"] if p["theme"] == theme["tag"]]
        noun = "map" if len(projects) == 1 else "maps"
        parts.append(f"## {theme['title']}\n\n{len(projects)} {noun}\n")
        cards = "\n".join(card(p, config) for p in projects)
        parts.append(f'<div class="gallery-grid">\n{cards}\n</div>\n')
    return "\n".join(parts)


def main():
    """Write ``docs/gallery.md``, or check it with ``--check``."""
    config = json.loads(SRC.read_text(encoding="utf-8"))
    tags = {t["tag"] for t in config["themes"]}
    for project in config["projects"]:
        if project["theme"] not in tags:
            sys.exit(f"{project['slug']}: unknown theme {project['theme']!r}")
        if len(project["caption"]) > 90:
            sys.exit(f"{project['slug']}: caption is over 90 characters")
    text = render(config)
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            sys.exit(
                "docs/gallery.md is out of date: run python scripts/build-gallery-docs.py"
            )
        print("docs/gallery.md is up to date")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(config['projects'])} projects)")


if __name__ == "__main__":
    main()
